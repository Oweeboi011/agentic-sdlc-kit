"""Write rendered files into a project or diff them (`--check`): marker, project sections, stale files."""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from pathlib import Path

MARKER = "generated by agentic-sdlc-kit {version}; edit the kit, not this file; sha256={digest}"
MARKER_RE = re.compile(
    r"^(?:<!-- |# )generated by agentic-sdlc-kit (\S+); edit the kit, not this file; "
    r"sha256=([0-9a-f]{64})(?: -->)?$",
    re.MULTILINE,
)
PROJECT = "<!-- project -->"
PROJECT_SPLIT = f"\n{PROJECT}\n"
PRESERVED = frozenset({"AGENTS.md", ".claude/CLAUDE.md", ".github/pull_request_template.md"})
EXECUTABLE = ".githooks/"
MANAGED_DIRS = (
    ".github/agents",
    ".github/instructions",
    ".github/skills",
    ".claude/agents",
    ".claude/skills",
    ".github/ISSUE_TEMPLATE",
    ".githooks",
)


@dataclass(frozen=True)
class Change:
    path: str
    reason: str
    content: str | None  # None deletes the file

    def __str__(self) -> str:
        return f"{self.path}: {self.reason}"


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def stamp(generated: str, version: str, rel: str = "") -> str:
    """Insert the marker after frontmatter or a shebang (both must stay on line 1), else at the top."""
    if generated.startswith("---\n"):
        at = generated.index("\n---\n") + 5
    else:
        at = generated.index("\n") + 1 if generated.startswith("#!") else 0
    marker = MARKER.format(version=version, digest=digest(generated))
    marker = f"<!-- {marker} -->" if not rel or rel.endswith(".md") else f"# {marker}"
    return f"{generated[:at]}{marker}\n{generated[at:]}"


def unstamp(text: str) -> tuple[str, str] | None:
    """Return (recorded hash, content without the marker line), or None if the file has no marker."""
    match = MARKER_RE.search(text)
    return None if match is None else (match.group(2), text[: match.start()] + text[match.end() + 1 :])


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (FileNotFoundError, UnicodeDecodeError):
        return None


def _reason(current: str | None, generated_part: str) -> str:
    if current is None:
        return "missing"
    found = unstamp(generated_part)
    if found is None:
        return "adopted: existing text kept below " + PROJECT
    return "hand-edited" if digest(found[1]) != found[0] else "out of date"


def _wanted(rel: str, current: str | None, stamped: str) -> tuple[str, str] | None:
    """Return (wanted file, current generated part), or None when a project-owned file blocks the path."""
    if rel not in PRESERVED:
        if current is not None and not MARKER_RE.search(current):
            return None
        return stamped, current or ""
    head, sep, tail = (current or "").partition(PROJECT_SPLIT)
    if current is not None and not MARKER_RE.search(head):
        head, tail = "", current
    elif not sep:
        tail = ""
    return f"{stamped}{PROJECT_SPLIT}{tail}", head


def plan(project: Path, rendered: dict[str, str], version: str) -> tuple[list[Change], list[str]]:
    changes: list[Change] = []
    conflicts: list[str] = []
    for rel, generated in rendered.items():
        current = _read(project / rel)
        wanted = _wanted(rel, current, stamp(generated, version, rel))
        if wanted is None:
            conflicts.append(f"{rel}: exists and was not generated by the kit; rename or delete it")
        elif current != wanted[0]:
            changes.append(Change(rel, _reason(current, wanted[1]), wanted[0]))
    for managed in MANAGED_DIRS:
        for path in sorted((project / managed).rglob("*")):
            rel = path.relative_to(project).as_posix()
            text = _read(path) if path.is_file() and rel not in rendered else None
            if text is not None and MARKER_RE.search(text):
                changes.append(Change(rel, "no longer rendered", None))
    return changes, conflicts


def apply(project: Path, changes: list[Change]) -> None:
    for change in changes:
        path = project / change.path
        if change.content is None:
            path.unlink()
            if not any(path.parent.iterdir()):
                path.parent.rmdir()
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(change.content, encoding="utf-8", newline="\n")
        if change.path.startswith(EXECUTABLE):
            path.chmod(0o755)


def write_starters(project: Path, files: dict[str, str]) -> tuple[list[str], list[str]]:
    """Write starter files the project lacks; from then on they belong to the project (no marker)."""
    created: list[str] = []
    kept: list[str] = []
    for rel, text in files.items():
        path = project / rel
        if path.exists():
            kept.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        created.append(rel)
    return created, kept
