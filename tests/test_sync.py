import os
import shutil
from pathlib import Path

import pytest

from kit_sync import cli
from kit_sync.sync import digest, stamp, unstamp

FIXTURES = Path(__file__).parent / "fixtures"
KIT = FIXTURES / "kit"
EXPECTED = FIXTURES / "expected"


@pytest.fixture(autouse=True)
def fixed_version(monkeypatch):
    monkeypatch.setattr(cli, "__version__", "0.0.0-golden")


@pytest.fixture
def project(tmp_path: Path) -> Path:
    root = tmp_path / "project"
    shutil.copytree(FIXTURES / "project", root)
    return root


def sync(project: Path, *flags: str) -> int:
    return cli.main([*flags, "--kit", str(KIT), "--project", str(project)])


def tree(root: Path) -> dict[str, str]:
    return {
        p.relative_to(root).as_posix(): p.read_text(encoding="utf-8")
        for p in sorted(root.rglob("*"))
        if p.is_file()
    }


def test_render_matches_golden_output(project):
    assert sync(project) == 0
    if os.environ.get("UPDATE_GOLDEN"):
        shutil.rmtree(EXPECTED, ignore_errors=True)
        shutil.copytree(project, EXPECTED)
    assert tree(project) == tree(EXPECTED)


def test_second_run_changes_nothing_and_check_passes(project, capsys):
    sync(project)
    capsys.readouterr()
    assert sync(project) == 0
    assert capsys.readouterr().out.startswith("0 file(s) updated")
    assert sync(project, "--check") == 0


def test_check_catches_hand_edit_and_render_restores_it(project, capsys):
    sync(project)
    agent = project / ".github/agents/coder.agent.md"
    agent.write_text(agent.read_text(encoding="utf-8") + "extra rule\n", encoding="utf-8")
    capsys.readouterr()
    assert sync(project, "--check") == 1
    assert ".github/agents/coder.agent.md: hand-edited" in capsys.readouterr().out
    sync(project)
    assert sync(project, "--check") == 0


def test_project_section_survives_and_is_not_drift(project):
    sync(project)
    agents = project / "AGENTS.md"
    agents.write_text(agents.read_text(encoding="utf-8") + "\nProject rule: keep me.\n", encoding="utf-8")
    assert sync(project, "--check") == 0
    sync(project)
    assert agents.read_text(encoding="utf-8").endswith("Project rule: keep me.\n")


def test_disabled_agent_files_are_stale_then_deleted(project, capsys):
    sync(project)
    config = project / ".github/astral-kit.yml"
    config.write_text(
        config.read_text(encoding="utf-8").replace("[planner, coder]", "[planner]"), encoding="utf-8"
    )
    capsys.readouterr()
    assert sync(project, "--check") == 1
    out = capsys.readouterr().out
    assert ".claude/agents/coder.md: no longer rendered" in out
    assert ".claude/skills/tdd/SKILL.md: no longer rendered" in out
    sync(project)
    assert not (project / ".claude/agents/coder.md").exists()
    assert not (project / ".claude/skills/tdd").exists()


def test_project_owned_file_is_never_overwritten(project, capsys):
    owned = project / ".claude/agents/planner.md"
    owned.parent.mkdir(parents=True)
    owned.write_text("hand-written agent\n", encoding="utf-8")
    assert sync(project) == 1
    assert "was not generated by the kit" in capsys.readouterr().out
    assert owned.read_text(encoding="utf-8") == "hand-written agent\n"
    assert not (project / ".github/agents").exists()


def test_new_kit_version_is_out_of_date(project, monkeypatch, capsys):
    sync(project)
    monkeypatch.setattr(cli, "__version__", "0.0.1")
    capsys.readouterr()
    assert sync(project, "--check") == 1
    assert "AGENTS.md: out of date" in capsys.readouterr().out


def test_copilot_only_puts_skills_under_github(project):
    config = project / ".github/astral-kit.yml"
    text = config.read_text(encoding="utf-8").replace("[copilot, claude-code]", "[copilot]")
    config.write_text(text, encoding="utf-8")
    sync(project)
    assert (project / ".github/skills/tdd/SKILL.md").is_file()
    assert not (project / ".claude").exists()


def test_invalid_config_renders_nothing(project, capsys):
    (project / ".github/astral-kit.yml").write_text("kit: v0\n", encoding="utf-8")
    assert sync(project) == 1
    assert "nothing rendered" in capsys.readouterr().out
    assert not (project / ".github/agents").exists()


@pytest.mark.parametrize("text", ["plain\n", "---\nname: x\n---\nbody\n"])
def test_stamp_round_trips(text):
    recorded, content = unstamp(stamp(text, "v1.2.3"))
    assert content == text
    assert recorded == digest(text)
